        "random.seed(SEED + 1)",
        "val_gen = mixed_text_stream()",
        "",
        "val_stats = {L: {'mse': 0.0, 'var_total': 0.0, 'residual_sq': 0.0, 'l0_sum': 0, 'l0_n': 0, 'fired': set()} for L in LAYERS}",
