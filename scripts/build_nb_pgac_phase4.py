        "        for _ in range(n_iter):",
        "            d = (samples - med).norm(dim=-1).clamp_min(1e-8)",
        "            w = 1.0 / d",
        "            med = (samples * w.unsqueeze(1)).sum(0) / w.sum()",
        "        self.b_dec.data = med.to(self.b_dec.dtype)",
        "",
        "# Smoke",
